import { expect, test } from "@jest/globals";

import { SIGN_VOCABULARY } from "./signDictionary";
import { planSigns } from "./signPlan";

const VOCABULARY = new Set(["сайн байна уу", "баярлалаа", "уучлаарай", "баяртай", "туслах"]);

test("a known whole sentence uses its curated phrase sign", () => {
  expect(planSigns("Таньд юугаар туслах вэ?", VOCABULARY)).toEqual({
    kind: "phrase", phrase: "helpQuestion", words: ["туслах"],
  });
});

test("any other sentence falls back to key-word signs", () => {
  expect(planSigns("Би одоо танд туслана", VOCABULARY)).toEqual({ kind: "keywords", words: ["туслах"] });
});

test.each(["Танд туслахгүй", "Өнөөдөр цаг агаар сайхан", ""])("«%s» shows text only", (transcript) => {
  expect(planSigns(transcript, VOCABULARY)).toBeNull();
});

// Жинхэнэ mnsl.mn толь бичгээр: үйлчилгээний газарт ихэвчлэн хэлдэг өгүүлбэрүүд.
test.each<[string, string[]]>([
  ["Та 10 дугаарын цонхонд очно уу", ["та", "10", "цонх", "очих"]],
  ["Гуравдугаар цонх руу очно уу", ["3", "цонх", "очих"]],
  ["Хоёрдугаар давхарт гарна уу", ["2", "гарах"]],
  ["Та 5 дугаар цонхонд ирнэ үү", ["та", "5", "цонх", "ирэх"]],
  ["Дараагийн хүн орно уу", ["хүн", "орох"]],
  ["Та түр хүлээгээрэй", ["та", "хүлээх"]],
  ["Иргэний үнэмлэхээ үзүүлнэ үү", ["иргэний үнэмлэх"]],
  ["Төлбөрөө картаар төлөх үү", ["төлбөр", "төлөх"]],
  ["Утасны дугаараа хэлнэ үү", ["утас", "хэлэх"]],
  ["Эмч таныг дуудаж байна", ["эмч", "та", "дуудах"]],
  ["Хаана өвдөж байна вэ", ["хаана", "өвдөх"]],
  ["Энэ эмийг өдөрт гурван удаа уугаарай", ["өдөр", "3", "уух"]],
  ["Цусны шинжилгээ өгнө үү", ["цус", "шинжилгээ", "өгөх"]],
  ["Маргааш өглөө дахин ирээрэй", ["өглөө", "дахин", "ирэх"]],
  ["Энэ мянган төгрөг", ["1000"]],
  ["Таны нэр хэн бэ", ["та", "нэр", "хэн"]],
  ["Та хаанаас ирсэн бэ", ["та", "хаана", "ирэх"]],
  ["Ажил хэдэн цагт эхлэх вэ", ["ажил", "хэд", "цаг", "эхлэх"]],
  ["Уучлаарай, давтана уу", ["уучлаарай", "давтах"]],
])("«%s» → %j with the real dictionary", (transcript, words) => {
  expect(planSigns(transcript, SIGN_VOCABULARY)?.words).toEqual(words);
});
